"""Figures and tables for the V3 manuscript from the two 2026-09-20 campaigns.

  python -m studies.revision.figures_v3 --shared runs/revision/shared_decoded \
      --inventory runs/revision/inventory_campaign --out submission/v3

Reads only final.json / summary.json files; writes figures/*.pdf and tables/*.tex.
"""
import argparse
import json
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

NAVY, JEPA, REAL, FLOW = "#17324D", "#CD663E", "#087E83", "#7860A5"
WORLDS = [("gray_frame_still", "per-frame noise\nno wind"), ("gray_frame_wind", "per-frame noise\nwind"),
          ("gray_episode_wind", "persistent noise\nwind"), ("gate", "gate")]


def wilson(k, n, z=1.96):
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)


def shared_rows(root):
    rows = []
    for f in sorted(Path(root).glob("policies/*/*/*/p*/final.json")):
        d = json.loads(f.read_text())
        if d.get("smoke"):
            continue
        m = d["metrics"]
        ledger = f.with_name("ledger.jsonl")
        imagined = math.nan
        if d["train_source"] == "dream" and ledger.exists():
            last = json.loads(ledger.read_text().strip().splitlines()[-1])
            imagined = last.get("reward", math.nan)
        rows.append(dict(world=d["world"], family=d["family"], source=d["train_source"], seed=d["policy_seed"],
                         survival=m["survival"], walls=m.get("walls_passed", math.nan),
                         length=m.get("control_length", m.get("length", math.nan)), ret=m["return"],
                         imagined_reward=imagined))
    return rows


def fmt(vals):
    vals = [v for v in vals if not (isinstance(v, float) and math.isnan(v))]
    if not vals:
        return "--"
    if len(vals) == 1:
        return f"${vals[0]:.2f}$"
    return f"${np.mean(vals):.2f}\\pm{np.std(vals, ddof=1):.2f}$"


def shared_table(rows, out):
    lines = ["% generated by studies/revision/figures_v3.py from runs/revision/shared_decoded",
             "\\begin{tabular}{llrrrr}", "\\toprule", "\\rowcolor{Navy!8}",
             "World & Training / model & Survival & Walls & Imagined $r$ & Seeds \\\\", "\\midrule"]
    def block(world, label, source, fam, color):
        sel = [r for r in rows if r["world"] == world and r["source"] == source and r["family"] == fam]
        if not sel:
            return
        s = [r["survival"] for r in sel]
        w = [r["walls"] for r in sel] if world == "gate" else []
        im = [r["imagined_reward"] for r in sel] if source == "dream" else []
        lines.append(f"\\rowcolor{{{color}!7}}" if color else "")
        lines.append(f"{label} & {'real, decoded ' if source == 'real' else 'imagined, '}{fam.upper() if fam == 'jepa' else 'flow'} & "
                     f"{fmt(s)} & {fmt(w) if w else '--'} & {fmt(im) if im else '--'} & {len(sel)} \\\\")
    for world, label in WORLDS:
        label = label.replace("\n", ", ")
        before = len(lines)
        if world == "gate":
            block(world, label, "real", "jepa", "Real")
            block(world, label, "real", "flow", "Real")
        block(world, label, "dream", "jepa", "JEPA")
        block(world, label, "dream", "flow", "Flow")
        if len(lines) > before:
            lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines.append("\\end{tabular}")
    Path(out).write_text("\n".join(l for l in lines if l is not None) + "\n")


def shared_figure(rows, out):
    fig, axes = plt.subplots(1, 4, figsize=(11, 2.9), sharey=True, gridspec_kw=dict(width_ratios=[1, 1, 1, 1.6]))
    for ax, (world, label) in zip(axes, WORLDS):
        groups = [("dream", "jepa", JEPA, "JEPA\nimagined"), ("dream", "flow", FLOW, "flow\nimagined")]
        if world == "gate":
            groups = [("real", "jepa", REAL, "JEPA\nreal"), ("real", "flow", REAL, "flow\nreal")] + groups
        xs, labels = [], []
        for i, (source, fam, color, name) in enumerate(groups):
            sel = [r for r in rows if r["world"] == world and r["source"] == source and r["family"] == fam]
            ys = [r["survival"] for r in sel]
            if ys:
                jitter = np.linspace(-0.12, 0.12, len(ys)) if len(ys) > 1 else np.zeros(1)
                ax.scatter(i + jitter, ys, s=42, color=color, zorder=3,
                           marker="o" if fam == "jepa" else "s", edgecolor="white", linewidth=0.6)
                ax.hlines(np.mean(ys), i - 0.25, i + 0.25, color=color, linewidth=2.2, zorder=2)
            xs.append(i)
            labels.append(name)
        ax.set_xticks(xs)
        ax.set_xticklabels(labels, fontsize=8)
        ax.set_xlim(-0.6, len(groups) - 0.4)
        ax.set_ylim(-0.03, 1.03)
        ax.set_title(label.replace("\n", ", "), fontsize=9.5, color=NAVY)
        ax.grid(axis="y", alpha=0.25)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    axes[0].set_ylabel("survival (256 paired episodes)", fontsize=9)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    fig.savefig(str(out).replace(".pdf", ".png"), dpi=200, bbox_inches="tight")
    plt.close(fig)


def inventory_rows(root):
    rows = []
    for f in sorted(Path(root).glob("*/native/summary.json")):
        d = json.loads(f.read_text())
        if not d.get("reportable"):
            continue
        name = f.parent.parent.name
        fam, seed = name.split("_p")
        a = d["all_22_achievement_rates"]
        trace = f.parent.parent / "training.jsonl"
        imagined = math.nan
        if trace.exists():
            imagined = json.loads(trace.read_text().strip().splitlines()[-1]).get("learned_reward_mean", math.nan)
        rows.append(dict(family=fam, seed=int(seed), pickaxe=d["primary"]["successes"], n=d["primary"]["n"],
                         achievements=d["achievement_count"]["mean"], ret=d["native_return"]["mean"],
                         steps=d["executed_steps"]["mean"], wood=a["COLLECT_WOOD"]["rate"],
                         table=a["PLACE_TABLE"]["rate"], stone=a["COLLECT_STONE"]["rate"], imagined_reward=imagined))
    for name in ("random", "noop"):
        f = Path(root) / "reference" / name / "summary.json"
        if f.exists():
            d = json.loads(f.read_text())
            a = d["all_22_achievement_rates"]
            rows.append(dict(family=name, seed=-1, pickaxe=d["primary"]["successes"], n=d["primary"]["n"],
                             achievements=d["achievement_count"]["mean"], ret=d["native_return"]["mean"],
                             steps=d["executed_steps"]["mean"], wood=a["COLLECT_WOOD"]["rate"],
                             table=a["PLACE_TABLE"]["rate"], stone=a["COLLECT_STONE"]["rate"]))
    return rows


def inventory_table(rows, out):
    lines = ["% generated by studies/revision/figures_v3.py from runs/revision/inventory_campaign",
             "\\begin{tabular}{llrrrrrr}", "\\toprule", "\\rowcolor{Navy!8}",
             "Policy trained in & seed & wood & table & pickaxe & achievements & return & imagined $r$ \\\\", "\\midrule"]
    for fam, color, label in (("flow", "Flow", "flow imagination"), ("jepa", "JEPA", "JEPA imagination")):
        for r in sorted([r for r in rows if r["family"] == fam], key=lambda r: r["seed"]):
            lines.append(f"\\rowcolor{{{color}!7}}")
            lines.append(f"{label} & {r['seed']} & {100 * r['wood']:.0f}\\% & {100 * r['table']:.0f}\\% & "
                         f"{r['pickaxe']}/{r['n']} & {r['achievements']:.2f} & {r['ret']:.2f} & {r['imagined_reward']:.2f} \\\\")
    refs = [r for r in rows if r["seed"] < 0]
    if refs:
        lines.append("\\midrule")
        for r in refs:
            lines.append(f"{'uniform random' if r['family'] == 'random' else 'no-op'} & -- & {100 * r['wood']:.0f}\\% & "
                         f"{100 * r['table']:.0f}\\% & {r['pickaxe']}/{r['n']} & {r['achievements']:.2f} & {r['ret']:.2f} & -- \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    Path(out).write_text("\n".join(lines) + "\n")


def inventory_figure(rows, out):
    fig, axes = plt.subplots(1, 2, figsize=(8.2, 2.9))
    order = [("flow", FLOW, "flow\nimagination"), ("jepa", JEPA, "JEPA\nimagination"), ("random", "#888888", "uniform\nrandom")]
    for ax, (key, ylabel) in zip(axes, (("pickaxe", "wood pickaxe rate (256 episodes)"), ("achievements", "achievements per episode"))):
        xs, labels = [], []
        for i, (fam, color, name) in enumerate(order):
            sel = sorted([r for r in rows if r["family"] == fam], key=lambda r: r["seed"])
            if not sel:
                continue
            for j, r in enumerate(sel):
                x = i + (np.linspace(-0.15, 0.15, len(sel))[j] if len(sel) > 1 else 0)
                if key == "pickaxe":
                    y = r["pickaxe"] / r["n"]
                    lo, hi = wilson(r["pickaxe"], r["n"])
                    ax.errorbar(x, y, yerr=[[y - lo], [hi - y]], fmt="o", color=color, ms=5.5, capsize=2, lw=1)
                else:
                    ax.scatter(x, r[key], color=color, s=40, zorder=3)
            xs.append(i)
            labels.append(name)
        ax.set_xticks(xs)
        ax.set_xticklabels(labels, fontsize=8.5)
        ax.set_ylabel(ylabel, fontsize=9)
        ax.grid(axis="y", alpha=0.25)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    axes[0].set_ylim(-0.03, 1.03)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    fig.savefig(str(out).replace(".pdf", ".png"), dpi=200, bbox_inches="tight")
    plt.close(fig)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--shared", type=Path)
    p.add_argument("--inventory", type=Path)
    p.add_argument("--out", type=Path, required=True)
    a = p.parse_args()
    (a.out / "figures").mkdir(parents=True, exist_ok=True)
    (a.out / "tables").mkdir(parents=True, exist_ok=True)
    if a.shared:
        rows = shared_rows(a.shared)
        shared_table(rows, a.out / "tables" / "shared_cnn.tex")
        shared_figure(rows, a.out / "figures" / "shared_cnn.pdf")
        print(f"shared: {len(rows)} policies")
    if a.inventory:
        rows = inventory_rows(a.inventory)
        inventory_table(rows, a.out / "tables" / "inventory.tex")
        inventory_figure(rows, a.out / "figures" / "inventory.pdf")
        print(f"inventory: {len(rows)} rows")


if __name__ == "__main__":
    main()
